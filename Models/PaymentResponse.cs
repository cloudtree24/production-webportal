namespace HCMPortal.Models
{
    public class PaymentResponse
    {
        public string? ResponseCode { get; set; }              // Response code (e.g., "0000", "R1000")
        public string? RespDescription { get; set; }           // Description of failure (ignore for success)
        public string? MerchantId { get; set; }                // Merchant account ID
        public string? AggregatorID { get; set; }              // Merchant aggregator ID
        public string? MerchantTxnNo { get; set; }             // Merchant Txn ref number
        public string? TxnID { get; set; }                     // Unique ref number generated by PG
        public string? PaymentDateTime { get; set; }           // Authorization date time (YYYYMMDDHHMISS)
        public string? PaymentID { get; set; }                 // Authorization/payment ID
        public string? PaymentMode { get; set; }               // Payment mode (CARD, NB, UPI, etc.)
        public string? PaymentSubInstType { get; set; }        // Sub instrument type (Bank name / DC / CC)
        public decimal? Amount { get; set; }                  // Amount paid
        public string? TxnChannel { get; set; }                // Channel (POS, WEB)
        public string? CustomerMobileNo { get; set; }          // Customer mobile number
        public string? CustomerEmailID { get; set; }           // Customer email ID
        public string? AddlParam1 { get; set; }                // Additional parameter 1
        public string? AddlParam2 { get; set; }                // Additional parameter 2
        public decimal? ConvenienceFee { get; set; }          // Convenience fee charged
        public decimal? ServiceTax { get; set; }              // Service tax
        public string? CardNetwork { get; set; }               // Card network
        public string? NwAuthRefNo { get; set; }               // Network Auth reference number
        public string? PanReferenceId { get; set; }            // PAN reference ID
        public string? MaskedCardNo { get; set; }              // Masked card number
        public string? TokenReferenceId { get; set; }          // Token reference ID
        public string? TokenReferenceIdHash { get; set; }      // Token reference ID hash
        public string? CardExpiry { get; set; }                // Card expiry (YYYYMM)
        public string? SecureHash { get; set; }
        // Additional customer details Daitari(25-11-2025)
        public string? Name { get; set; }
        public string? Email { get; set; }
        public string? Phone { get; set; }
       
        public string? OrderId { get; set; }
     
        public string? Status { get; set; }// Secure hash for verification
        public string? ErrorMessage { get; set; }// Secure hash for verification
        public string? OrderType { get; set; }
    }

}
